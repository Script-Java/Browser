// Builds the scripts the app injects into pages into src/scripts/generated.ts,
// as strings. They ship inside the signed app and are never fetched from the
// server. Run `pnpm build:scripts` after changing scripts/inject or the old
// app's fingerprint.js, and commit the result.
//
// esbuild and autoconsent come from the old app's node_modules (`pnpm install`
// in ../app first), so both apps run the same versions.

import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const here = import.meta.dirname;
const appModules = resolve(here, "../../app/node_modules");
const { build } = createRequire(resolve(appModules, "..", "package.json"))("esbuild");

async function bundle(entry, define) {
	const result = await build({
		entryPoints: [resolve(here, "inject", entry)],
		nodePaths: [appModules],
		bundle: true,
		format: "iife",
		minify: true,
		write: false,
		target: ["ios26"],
		// keeps the notices the open-source libraries bundled here ask for
		legalComments: "inline",
		define,
	});
	return result.outputFiles[0].text;
}

const scripts = {
	fingerprintStandard: await bundle("fingerprint.js", { __LEVEL__: '"standard"' }),
	fingerprintSafer: await bundle("fingerprint.js", { __LEVEL__: '"safer"' }),
	gpc: await bundle("gpc.js"),
	relay: await bundle("relay.js"),
	noCredentials: await bundle("no-credentials.js"),
	consent: await bundle("consent.js"),
};

const out = resolve(here, "../src/scripts/generated.ts");
writeFileSync(
	out,
	"// Generated by scripts/build-scripts.mjs (pnpm build:scripts). Don't edit.\n" +
		Object.entries(scripts)
			.map(([name, text]) => `export const ${name} = ${JSON.stringify(text)};\n`)
			.join("")
);
console.log(`${out}: ${Object.entries(scripts).map(([name, text]) => `${name} ${(text.length / 1024).toFixed(1)} KB`).join(", ")}`);
